// Writes src/api/generated.ts from the running server's description of itself.
//
//   bun run generate
//
// The file holds the input type of every command (from its JSON Schema) and the
// names of the entities and document types. The API client is typed with it, so
// a change on the server breaks the UI build instead of a user's screen.

import { writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { asArray, asObject, asString, type Json, type JsonObject, SERVER, signIn } from "./lib";
import { schemaToType, withNamedRefs } from "./schema-to-type";

const session = await signIn();
const meta = asObject(await session.get("/api/meta"));

const names = (key: string): string[] =>
  asArray(meta[key])
    .map((entry) => asString(asObject(entry).name))
    .sort();

function union(values: string[]): string {
  return values.length === 0 ? "never" : values.map((v) => JSON.stringify(v)).join(" | ");
}

function pascal(name: string): string {
  return name
    .split(/[._]/)
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join("");
}

function comment(text: string, indent: string): string {
  const lines = text.trim().split("\n");
  return `${indent}/**\n${lines.map((l) => `${indent} * ${l.replaceAll("*/", "* /")}`).join("\n")}\n${indent} */\n`;
}

interface Command {
  name: string;
  description: string;
  readOnly: boolean;
  schema: JsonObject;
  output: JsonObject | null;
}

const commands: Command[] = asArray(meta.commands)
  .map((entry: Json) => {
    const command = asObject(entry);
    return {
      name: asString(command.name),
      description: typeof command.description === "string" ? command.description : "",
      readOnly: command.read_only === true,
      schema: asObject(command.input_schema),
      output:
        command.output_schema && typeof command.output_schema === "object" && !Array.isArray(command.output_schema)
          ? command.output_schema
          : null,
    };
  })
  .sort((a, b) => a.name.localeCompare(b.name));

let out = `// GENERATED by scripts/generate-api-types.ts from GET /api/meta. Do not edit.
// Regenerate with \`bun run generate\` while the server is running.

/** Any JSON value. Used where a command's schema leaves a value open. */
export type Json = null | boolean | number | string | Json[] | { [key: string]: Json };

export type EntityName = ${union(names("entities"))};

export type DocTypeName = ${union(names("doc_types"))};

export type ModuleName = ${union(names("modules"))};

`;

for (const command of commands) {
  out += comment(command.description || command.name, "");
  out += `export type ${pascal(command.name)}Input = ${schemaToType(command.schema, command.schema, "")};\n\n`;
}

// ----------------------------------------------------------------- outputs
//
// The shapes that output schemas share (`$defs`) become named types, so the UI
// can import `FieldMeta` or `PostingView` by name. A name that means different
// things in two commands gets the command's name in front.

const shared = new Map<string, string>();
const sharedOrder: string[] = [];

function nameFor(command: Command, ref: string, root: JsonObject): string | null {
  const match = /^#\/\$defs\/([A-Za-z0-9_]+)$/.exec(ref);
  const defs = root.$defs;
  if (!match?.[1] || !defs || typeof defs !== "object" || Array.isArray(defs)) return null;
  const definition = defs[match[1]];
  if (definition === undefined) return null;
  const text = withNamedRefs(
    (inner, innerRoot) => nameFor(command, inner, innerRoot),
    () => schemaToType(definition, root, ""),
  );
  for (const candidate of [match[1], `${pascal(command.name)}${match[1]}`]) {
    const existing = shared.get(candidate);
    if (existing === undefined) {
      shared.set(candidate, text);
      sharedOrder.push(candidate);
      return candidate;
    }
    if (existing === text) return candidate;
  }
  return null;
}

let outputs = "";
for (const command of commands) {
  const schema = command.output;
  const type = schema
    ? withNamedRefs(
        (ref, root) => nameFor(command, ref, root),
        () => schemaToType(schema, schema, ""),
      )
    : "Json";
  outputs += `export type ${pascal(command.name)}Output = ${type};\n\n`;
}

for (const name of sharedOrder) out += `export type ${name} = ${shared.get(name)};\n\n`;
out += outputs;
out +=
  "/** The output of every command, by command name, as far as the server describes it. */\nexport interface CommandOutputs {\n";
for (const command of commands) {
  out += `  ${JSON.stringify(command.name)}: ${pascal(command.name)}Output;\n`;
}
out += "}\n\n";

out += "/** The input of every command, by command name. */\nexport interface CommandInputs {\n";
for (const command of commands) {
  out += `  ${JSON.stringify(command.name)}: ${pascal(command.name)}Input;\n`;
}
out += "}\n\nexport type CommandName = keyof CommandInputs;\n\n";
out += `/** Commands that only read. */\nexport type ReadOnlyCommandName = ${union(commands.filter((c) => c.readOnly).map((c) => c.name))};\n`;

const target = resolve(import.meta.dir, "../src/api/generated.ts");
writeFileSync(target, out);
console.log(
  `${commands.length} commands, ${names("entities").length} entities, ${names("doc_types").length} document types from ${SERVER}`,
);
console.log(`wrote ${target}`);
